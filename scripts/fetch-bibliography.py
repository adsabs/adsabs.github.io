"""Pull the Bibliography page's paper lists from the SciX/ADS API.

Reads the token from SCIX_DEV_KEY, ADS_DEV_KEY, ADS_API_KEY, or ~/.ads/dev_key.
The token is never printed. Writes _data/bibliography.yml.

Four sources, each its own section on the page:

    papers about ADS/SciX        the public "ADS Refereed Papers" and
                                 "ADS Non-Refereed Papers" SciX libraries
    papers citing them           citations() of everything in those libraries
    papers acknowledging us      ack: mentions of ADS, Science Explorer, SciX
    team research                orcid: of every team member in _data/team.yml

Only the newest few records of each section are stored; the page links to the
full search in SciX for the rest. Citation counts are left out on purpose, so
the file only changes when a section gains or loses papers, and the weekly
workflow only opens a PR when there is something new.

    python3 scripts/fetch-bibliography.py
"""
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

API = "https://api.adsabs.harvard.edu/v1/search/query"
SCIX = "https://scixplorer.org"

REFEREED_LIBRARY = "aI9-ox_2RNeZK-gm-4DpVQ"
NON_REFEREED_LIBRARY = "iETdWs2pSGajhFBI30X3UQ"
CITING = (f"(citations(docs(library/{REFEREED_LIBRARY})) OR "
          f"citations(docs(library/{NON_REFEREED_LIBRARY})))")
ACK = 'ack:("Astrophysics Data System" OR "Science Explorer" OR "SciX")'
AUTHORS_SHOWN = 3


def token():
    for var in ("SCIX_DEV_KEY", "ADS_DEV_KEY", "ADS_API_KEY", "ADS_API_TOKEN"):
        if os.environ.get(var):
            return os.environ[var].strip()
    path = pathlib.Path.home() / ".ads" / "dev_key"
    if path.exists():
        return path.read_text().strip()
    sys.exit("No API token. Set SCIX_DEV_KEY or write the key to ~/.ads/dev_key")


def team_orcids():
    text = pathlib.Path("_data/team.yml").read_text()
    return re.findall(r'^\s+orcid:\s*"?([0-9X-]{19})"?\s*$', text, re.M)


def search(tok, query, rows):
    params = {"q": query, "fl": "bibcode,title,author,year,pub", "rows": rows,
              "sort": "date desc, bibcode desc"}
    url = API + "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {tok}"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=90) as r:
                return json.load(r)["response"]
        except urllib.error.HTTPError as e:
            # Large author lists occasionally time out at the gateway.
            if e.code in (502, 503, 504) and attempt < 3:
                time.sleep(10 * (attempt + 1))
                continue
            raise


def sections():
    orcid_query = "orcid:(" + " OR ".join(f'"{o}"' for o in team_orcids()) + ")"
    return [
        dict(id="team_refereed", title="Refereed papers about ADS and SciX",
             query=f"docs(library/{REFEREED_LIBRARY})", limit=25,
             link=f"{SCIX}/public-libraries/{REFEREED_LIBRARY}"),
        dict(id="team_non_refereed", title="Non-refereed papers about ADS and SciX",
             query=f"docs(library/{NON_REFEREED_LIBRARY})", limit=25,
             link=f"{SCIX}/public-libraries/{NON_REFEREED_LIBRARY}"),
        dict(id="citing_refereed", title="Refereed papers citing ADS/SciX literature",
             query=f"{CITING} property:refereed", limit=25),
        dict(id="citing_non_refereed", title="Non-refereed papers citing ADS/SciX literature",
             query=f"{CITING} -property:refereed", limit=25),
        dict(id="acknowledging", title="Papers acknowledging ADS or SciX",
             query=ACK, limit=10),
        dict(id="team_research", title="Research by ADS/SciX team members",
             query=orcid_query, limit=25),
    ]


def authors(names):
    shown = "; ".join(names[:AUTHORS_SHOWN])
    return shown + ("; et al." if len(names) > AUTHORS_SHOWN else "")


def q(value):
    """A YAML-safe scalar: JSON strings are valid YAML."""
    return json.dumps(value, ensure_ascii=False)


def main():
    tok = token()
    out = pathlib.Path("_data/bibliography.yml")
    with out.open("w") as f:
        f.write("# Generated by scripts/fetch-bibliography.py; do not edit by hand.\n")
        f.write("# Refreshed weekly by .github/workflows/bibliography.yml.\n")
        f.write("sections:\n")
        for s in sections():
            r = search(tok, s["query"], s["limit"])
            link = s.get("link") or (f"{SCIX}/search?" + urllib.parse.urlencode(
                {"q": s["query"], "sort": "date desc"}))
            print(f"  {s['id']:<20}{r['numFound']:>8,} total, {len(r['docs'])} stored")
            f.write(f"  - id: {s['id']}\n")
            f.write(f"    title: {q(s['title'])}\n")
            f.write(f"    total: {r['numFound']}\n")
            f.write(f"    link: {q(link)}\n")
            f.write("    papers:\n")
            for d in r["docs"]:
                f.write(f"      - bibcode: {q(d['bibcode'])}\n")
                f.write(f"        title: {q((d.get('title') or [''])[0])}\n")
                f.write(f"        authors: {q(authors(d.get('author') or []))}\n")
                f.write(f"        year: {q(d.get('year') or '')}\n")
                f.write(f"        pub: {q(d.get('pub') or '')}\n")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
